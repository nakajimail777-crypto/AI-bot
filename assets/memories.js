// Explicit, user-owned storage only. Nothing here participates in AI requests.
globalThis.DragonMemories = {
  async conversation(db, userId, conversationId) {
    await this.user(db,userId);
    const parts=[];
    let length=0;
    for(let offset=0;;offset+=200){
      const {data,error}=await db.from('messages').select('role,content,sequence')
        .eq('conversation_id',conversationId).eq('user_id',userId)
        .order('sequence',{ascending:true}).range(offset,offset+199);
      if(error || !Array.isArray(data))throw new Error('会話を読み込めませんでした。もう一度お試しください。');
      for(const row of data){
        const part=`${row.role==='user'?'あなた':'スピリットドラゴンAI'}\n${row.content}`;
        length+=part.length+(parts.length?2:0);
        if(length>100000)throw new Error('この会話は長いため保存できません（上限10万文字）。');
        parts.push(part);
      }
      if(data.length<200)break;
    }
    if(!parts.length)throw new Error('保存する会話がありません。');
    return parts.join('\n\n');
  },
  async user(db, expectedId) {
    const {data, error} = await db.auth.getUser();
    if (error || !data?.user || data.user.is_anonymous || data.user.id !== expectedId)
      throw new Error('ログインし直してください。');
    return data.user;
  },
  async save(db, userId, id, content) {
    await this.user(db, userId);
    // user_id is generated by auth.uid() in PostgreSQL.
    const {error} = await db.from('memories').insert({id, content});
    if (error && error.code !== '23505') throw new Error('記憶を保存できませんでした。もう一度お試しください。');
    if (error) {
      const result = await db.from('memories').select('id,content').eq('id',id).eq('user_id',userId).maybeSingle();
      if (result.error || result.data?.content !== content) throw new Error('保存を確認できませんでした。記憶一覧を確認してください。');
    }
  },
  async list(db, userId, offset = 0) {
    await this.user(db, userId);
    const {data,error} = await db.from('memories').select('id,content,created_at').eq('user_id',userId)
      .order('created_at',{ascending:false}).order('id',{ascending:false}).range(offset,offset+29);
    if (error) throw new Error('記憶一覧を読み込めませんでした。もう一度お試しください。');
    return data;
  },
  async remove(db, userId, id) {
    await this.user(db, userId);
    const {error} = await db.from('memories').delete().eq('id',id).eq('user_id',userId);
    if (error) throw new Error('記憶を削除できませんでした。もう一度お試しください。');
  }
};
