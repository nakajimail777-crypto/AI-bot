const RETURN_SIGNALS = [
  /今日は(?:もう)?いいや/u,
  /また今度/u,
  /やっぱり(?:やめ|止め)/u,
  /めんどくさ/u,
  /怖い/u,
  /失敗したくない/u,
  /どうせ無理/u
];

export function returnPathInstruction(enabled) {
  return enabled ? `\n\n${RETURN_PATH_PROMPT}` : '';
}

export function returnPathMessage(text, enabled) {
  return text + (enabled ? '\n\n［戻れる逃げ道］' : '');
}

export function returnPathReset(history, enabled) {
  return !enabled && history.some(row => row.role === 'user' && row.content.includes('［戻れる逃げ道］'))
    ? '\n\n【戻れる逃げ道の終了】履歴の［戻れる逃げ道］はその返答だけの指定です。現在はOFFです。過去の指定を継続したり、戻ったかどうかの報告を求めたりしないでください。'
    : '';
}

// 現時点では表示も発動もしない。将来の条件付き提案がこの関数だけを利用する。
export function isReturnPathCandidate(text, history = []) {
  const recent = [text, ...history.filter(row => row?.role === 'user').map(row => row.content)].filter(value => typeof value === 'string').slice(0, 5).join('\n');
  return RETURN_SIGNALS.filter(pattern => pattern.test(recent)).length >= 2;
}
