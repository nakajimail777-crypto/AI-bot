// Theme-led exploration shares the existing conversation and one generation request.
export function validateDeepRequest(body = {}) {
  const { deepTheme, deepAction } = body;
  if ((deepTheme !== undefined || deepAction !== undefined) && body.deepExploration !== true) {
    throw new Error('テーマと振り返りは「深く降りる」で選んでください。');
  }
  if (deepTheme !== undefined && (typeof deepTheme !== 'string' || /[\p{Cc}\p{Cf}\u2028\u2029]/u.test(deepTheme) || deepTheme.trim().length > 80)) {
    throw new Error('テーマは改行を入れず80文字以内で入力してください。');
  }
  if (deepAction !== undefined && (deepAction !== 'finish' || body.modeStart === true)) {
    throw new Error('振り返りは自己探索を始めてから選んでください。');
  }
  return { theme: deepTheme?.trim() || '', action: deepAction || null };
}

