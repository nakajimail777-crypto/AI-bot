export function deepMessage(text, start = false, { theme = '', action = null } = {}) {
  const message = start ? '［深く降りるを選択］' : text + '\n\n［深く降りる］';
  return message + (theme ? '\n［自己探索のテーマ：' + JSON.stringify(theme) + '］' : '') + (action === 'finish' ? '\n［深く降りるの振り返りを希望］' : '');
}
export function deepUserText(text, start = false, { theme = '' } = {}) {
  const message = start ? '深く降りるを開始します。今回選んだテーマ、または直前の話題から始めてください。' : text;
  return message + (theme ? '\n\n【今回選んだテーマ・参考データ】\n' + JSON.stringify({ theme }) + '\n【テーマここまで】' : '');
}

// Only a complete saved start record creates a boundary. A quoted marker in a
// normal message (or in an assistant reply) must not start another exploration.
export function deepSummaryRange(history = []) {
  for (let index = history.length - 1; index >= 0; index--) {
    const row = history[index];
    if (row?.role !== 'user' || typeof row.content !== 'string') continue;
    const match = row.content.match(/^［深く降りるを選択］(?:\n［自己探索のテーマ：(.+)］)?(?:\n\n［参照した記憶：[0-9a-f-]{36}］)?$/i);
    if (!match) continue;
    let theme = '';
    if (match[1]) {
      try { theme = JSON.parse(match[1]); } catch { continue; }
      if (typeof theme !== 'string') continue;
    }
    return { startIndex: index, messageCount: history.length - index, currentTopic: !theme };
  }
  return { startIndex: -1, messageCount: history.length, currentTopic: false };
}

function summaryScopeInstructions(history) {
  const scope = deepSummaryRange(history);
  if (scope.startIndex < 0) return '\n【振り返りの範囲が不明】直近の開始操作は現在の履歴に見つからない。開始時の話や今回の探索全体を覚えていると主張しない。取得できた直近の発言だけを参考にし、どの探索回の気持ちか分からないものは未確認に残す。';
  return '\n【今回の振り返りの範囲】このリクエストに含まれる会話履歴の' + (scope.startIndex + 1) + '件目にある本人の開始操作から末尾までの' + scope.messageCount + '件が、今回の探索区間である。開始より前は以前の会話であり、同じテーマでも今回とは別に扱う。本人が確認した気持ちとしてまとめてよいのは、この区間内で本人が語った、または具体的に確かめた内容だけ。以前の区間で確認済みだった感情やAIの要約を、今回の気づきへ持ち込まない。以前の内容は本人が今回あらためて述べたり確かめたりした場合のみ採用できる。'
    + (scope.currentTopic ? '今回は「今の話題」からの開始なので、開始直前に本人が話した場面は背景として参照してよい。ただし、その背景から今回の感情や発見を推定しない。' : '今回選んだテーマと今回の区間を対象にする。')
    + '開始直後に終了し、まだ気持ちを話していない場合も、未発見のままでよい。';
}

export function deepInstructions(active, start, history = [], { action = null } = {}) {
  if (active) return DEEP_RULES + (action === 'finish'
    ? '\n【今回の依頼：自己探索を終えて短く振り返る】探索を終了する。「最初に気になっていたこと」「本人が確認した気持ち」の二点を、それぞれ一文程度で短くまとめる。確認した気持ちは本人の最新の訂正を優先し、その言葉を短く引用する。「まだ分からないこと」は、最新の訂正後も本人が明示的に保留している発言がある場合だけその言葉を引用し、なければ項目自体を出さない。AIが考えた疑問や、まだ尋ねていない理由をこの項目へ補わない。本人の発言と確認を根拠にし、AIが提案しただけの仮説や、否定・保留された仮説を確認済みの気持ちにしない。見つからなければ「今回はまだ言葉になっていない」でよく、気持ちや未解決の問題を作らない。本人が書き直せる仮置きとして扱う。新しい質問、仮説、行動提案、次回の課題、「気持ちを確かめる」の見出しは付けず、ここで終える。' + summaryScopeInstructions(history)
    : start ? '\n今回はテーマを選んだボタン操作による開始。新しい体験の発言ではない。テーマがあれば、そのテーマで最近心に残った具体的な一場面を最大一問で尋ねる。既にその場面が話されていれば引き継ぎ、説明し直させない。テーマが空なら直前の話題から始め、話題もなければ今気になっていることを一つだけ尋ねる。直前に終了・疲労の希望があれば掘り始めず休む。' : '');
  return history.some(row => /［深く降りる(?:を選択)?］/.test(row.content || ''))
    ? '\n【自己探索の終了】履歴の深く降りるは過去の選択。今回は通常対話または現在選ばれたモードに従い、探索を自動継続しない。' : '';
}
